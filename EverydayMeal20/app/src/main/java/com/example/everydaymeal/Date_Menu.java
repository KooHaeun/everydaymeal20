package com.example.everydaymeal;

public class Date_Menu {
    public String date;
    public String date_menu;
    public String date_time;
    public String what;

    public String getDate() {
        return date;
    }

    public void setDate(String date) {
        this.date = date;
    }

    public String getDate_menu() {
        return date_menu;
    }

    public void setDate_menu(String date_menu) {
        this.date_menu = date_menu;
    }

    public String getDate_time() {
        return date_time;
    }

    public void setDate_time(String date_time) {
        this.date_time = date_time;
    }

    public String getWhat() {
        return what;
    }

    public void setWhat(String what) {
        this.what = what;
    }
}
